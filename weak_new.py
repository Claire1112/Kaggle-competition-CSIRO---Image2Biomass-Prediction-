        if model_output.ndim == 2:
            b, c = model_output.shape
            j = min(self.idx, c - 1)  # 如果只有 1 維，就用最後一維
            return model_output[0, j]

        # [C]
        if model_output.ndim == 1:
            c = model_output.shape[0]
            j = min(self.idx, c - 1)
            return model_output[j]

        # 其他奇怪情況：攤平後取第一個
        return model_output.view(-1)[0]

